import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await p.waitForSelector('#loader', { state: 'detached' });
await p.evaluate(() => document.getElementById('residences').scrollIntoView());
await p.waitForTimeout(1500);
const m = async () => p.evaluate(() => { const s = document.querySelector('.res__tabs [aria-selected=true]').getBoundingClientRect(), i = document.querySelector('.res__ind').getBoundingClientRect(); return { tab: [Math.round(s.left), Math.round(s.right), Math.round(s.bottom)], ind: [Math.round(i.left), Math.round(i.right), Math.round(i.bottom)] }; });
const a = await m();
await p.click('#tab-mp'); await p.waitForTimeout(250);
const mid = await m();
await p.waitForTimeout(600);
const c = await m();
await p.screenshot({ path: 'screenshots/polish-residences.png' });
await p.focus('#tab-mp'); await p.keyboard.press('ArrowLeft'); await p.waitForTimeout(30);
const k = await m(); const name = await p.textContent('#resName');
await p.setViewportSize({ width: 390, height: 844 }); await p.waitForTimeout(400);
const mob = await m();
console.log(JSON.stringify({ initial: a, midSlide: mid, settled: c, keyboardInstant: k, name, mobileAfterResize: mob, errs }));
await b.close();
